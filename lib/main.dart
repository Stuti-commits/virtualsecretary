// ── Auth Router ───────────────────────────────────────────────────────────────
//
// Flow:
//   Firebase says "not logged in"  →  LoginScreen
//   Firebase says "logged in" but no Firestore profile yet (new signup)  →  LoginScreen (AuthService loads profile)
//   Profile loaded, role == null / empty  →  RoleSelectionScreen
//   Profile loaded, role assigned  →  role-specific HomeScreen

class _AuthRouter extends StatelessWidget {
  const _AuthRouter();

  @override
  Widget build(BuildContext context) {
    return StreamBuilder<User?>(
      stream: context.read<AuthService>().authStateChanges,
      builder: (context, snapshot) {
        if (snapshot.connectionState == ConnectionState.waiting) {
          return const _SplashScreen();
        }

        final firebaseUser = snapshot.data;
        if (firebaseUser == null) return const LoginScreen();

        return Consumer<AuthService>(
          builder: (context, auth, _) {
            final appUser = auth.currentAppUser;

            if (appUser == null) {
              Future.microtask(() => auth.fetchUserProfile(firebaseUser.uid));
              return const _SplashScreen();
            }

            if (appUser.role == null) return const RoleSelectionScreen();

            switch (appUser.role!) {
              case UserRole.secretary:
                return const SecretaryHomeScreen();
              case UserRole.security:
                return const SecurityHomeScreen();
              case UserRole.resident:
                return const ResidentHomeScreen();
            }
          },
        );
      },
    );
  }
}
  @override
  Widget build(BuildContext context) {
    final authService = context.watch<AuthService>();

    return StreamBuilder<User?>(
      stream: authService.authStateChanges,
      builder: (context, snapshot) {
        // ── Loading (waiting for Firebase to initialise) ──────────
        if (snapshot.connectionState == ConnectionState.waiting) {
          return const _SplashScreen();
        }

        final firebaseUser = snapshot.data;

        // ── Not logged in ─────────────────────────────────────────
        if (firebaseUser == null) {
          return const LoginScreen();
        }

        // ── Logged in — fetch/use Firestore profile ───────────────
        return FutureBuilder<AppUser?>(
          // Only re-fetch if we don't already have a cached profile
          future: authService.currentAppUser != null
              ? Future.value(authService.currentAppUser)
              : authService.fetchUserProfile(firebaseUser.uid),
          builder: (context, profileSnap) {
            if (profileSnap.connectionState == ConnectionState.waiting) {
              return const _SplashScreen();
            }

            final appUser = profileSnap.data;

            // Profile doc missing (edge case: auth exists but Firestore write
            // failed) — send back to login so they can re-authenticate.
            if (appUser == null) {
              return const LoginScreen();
            }

            // Role not yet assigned → role selection
            if (appUser.role == null) {
              return const RoleSelectionScreen();
            }

            // Role-based routing
            switch (appUser.role) {
              case UserRole.secretary:
                return const SecretaryHomeScreen();
              case UserRole.security:
                return const SecurityHomeScreen();
              case UserRole.resident:
              default:
                return const ResidentHomeScreen();
            }
          },
        );
      },
    );
  }


